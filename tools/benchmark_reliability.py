"""Repetible offline benchmark for the MTF incremental PAPER paths.

The benchmark measures the existing application routes without changing their
durability contract:

* the bundled generated cTrader Protobuf codec is decoded when it is
  available; otherwise the run is explicitly labelled as fixture fallback;
* the same immutable capture is sent through the real cTrader pipeline;
* ``atomic_batch`` uses the public ``ingest_many`` path and ``unbatched`` uses
  one public ``ingest`` call per envelope;
* indicators, strategy decisions, checkpoints, SQLite projections and bounded
  ``QueryService`` reads are exercised;
* a speed pass disables ``tracemalloc`` while a separate memory pass enables
  it; wall/CPU statistics never include memory instrumentation;
* memory-pass allocation, process max RSS and temporary SQLite-artifact growth
  are reported separately from speed statistics.

This is an engineering measurement of local synthetic work. It is not a
broker, market, latency, fill or profitability benchmark. All databases and
HOME/XDG/TMP state are created below a temporary directory and are removed by
the end of the run. The output contains no temporary paths or payload dump.
"""

