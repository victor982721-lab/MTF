def _generated_spot(raw: Mapping[str, Any]) -> Any:
    """Build a generated SpotEvent from the wire-shaped fixture fields."""

    from mtf_lab.data.protobuf_generated import OpenApiMessages_pb2 as messages

    spot = messages.ProtoOASpotEvent(
        ctidTraderAccountId=7,
        symbolId=int(raw["symbolId"]),
        timestamp=int(raw["timestamp"]),
        bid=int(raw["bid"]),
        ask=int(raw["ask"]),
    )
    for raw_bar in raw.get("trendbar", ()):
        bar = spot.trendbar.add()
        for name in ("period", "low", "deltaOpen", "deltaClose", "deltaHigh", "utcTimestampInMinutes", "volume"):
            if name in raw_bar:
                setattr(bar, name, int(raw_bar[name]))
    return spot


def _encode_inputs(raw_payloads: Sequence[Mapping[str, Any]], codec: Any | None) -> tuple[bytes, ...]:
    if codec is None:
        return tuple(canonical_json(dict(payload)).encode("utf-8") for payload in raw_payloads)
    frames: list[bytes] = []
    for index, raw in enumerate(raw_payloads):
        try:
            payload = _generated_spot(raw)
            frames.append(
                codec.encode(
                    WireMessage(
                        PAYLOAD["PROTO_OA_SPOT_EVENT"],
                        payload,
                        client_msg_id=f"mtf-benchmark-{index}",
                    )
                )
            )
        except Exception as exc:
            raise BenchmarkError(f"no se pudo codificar fixture Protobuf en frame {index}") from exc
    return tuple(frames)


def _hash_frames(frames: Sequence[bytes], end_payload: Mapping[str, Any]) -> tuple[str, int]:
    digest = hashlib.sha256()
    total = 0
    for frame in frames:
        digest.update(len(frame).to_bytes(8, "big"))
        digest.update(frame)
        total += len(frame)
    end_text = canonical_json(end_payload).encode("utf-8")
    digest.update(len(end_text).to_bytes(8, "big"))
    digest.update(end_text)
    return digest.hexdigest(), total


def _end_envelope(event_count: int, end: datetime, first_available: datetime) -> CaptureEnvelope:
    return CaptureEnvelope(
        end,
        end,
        end,
        event_count,
        0,
        MessageClass.END,
        {
            "continuity": "CONTINUOUS",
            "requested_start": instant_text(first_available),
            "requested_end": instant_text(end),
        },
    )


def _mapping_envelope(raw: Mapping[str, Any], index: int, *, source: str) -> CaptureEnvelope:
    timestamp = datetime.fromtimestamp(int(raw["timestamp"]) / 1000, UTC)
    available = timestamp + timedelta(seconds=1)
    payload = dict(raw)
    # These are explicit fixture provenance fields, not claims about the wire
    # schema. They let the normalizer preserve synthetic status after decoding.
    payload.update({"synthetic_fixture": True, "snapshot": index == 0, "sequence": index})
    return CaptureEnvelope(
        timestamp,
        available,
        available,
        index,
        0,
        MessageClass.SPOT,
        payload,
        source_identity=source,
    )


def _wire_envelope(wire: WireMessage, index: int, *, source: str) -> CaptureEnvelope:
    raw = message_to_mapping(wire.payload)
    if not isinstance(raw, Mapping):
        raise BenchmarkError(f"frame {index} no produjo un mensaje generado mapeable")
    timestamp_value = raw.get("timestamp")
    if timestamp_value is None:
        raise BenchmarkError(f"frame {index} no contiene timestamp")
    timestamp = datetime.fromtimestamp(int(timestamp_value) / 1000, UTC)
    available = timestamp + timedelta(seconds=1)
    stamped = wire.with_capture_metadata(
        received_at=available,
        available_at=available,
        ingest_sequence=index,
        connection_generation=0,
        message_class="spot",
        source_identity=source,
    )
    row = wire_capture_envelope(stamped)
    payload = dict(cast(Mapping[str, Any], row["payload"]))
    payload.update({"synthetic_fixture": True, "snapshot": index == 0, "sequence": index})
    row["payload"] = payload
    return CaptureEnvelope.from_mapping(row)


def _decode_chunk(
    frames: Sequence[bytes],
    start_index: int,
    codec: Any | None,
    *,
    source: str,
) -> tuple[CaptureEnvelope, ...]:
    if codec is None:
        decoded: list[CaptureEnvelope] = []
        for offset, frame in enumerate(frames):
            try:
                raw = json.loads(frame.decode("utf-8"))
            except (UnicodeDecodeError, json.JSONDecodeError) as exc:
                raise BenchmarkError("fixture fallback JSON inválido") from exc
            if not isinstance(raw, Mapping):
                raise BenchmarkError("fixture fallback debe producir mapping")
            decoded.append(_mapping_envelope(raw, start_index + offset, source=source))
        return tuple(decoded)
    decoded_wire: list[CaptureEnvelope] = []
    for offset, frame in enumerate(frames):
        decoded_wire.append(_wire_envelope(codec.decode(frame), start_index + offset, source=source))
    return tuple(decoded_wire)


def _prepare_input(seed: int, event_count: int) -> _PreparedInput:
    start = BASE + timedelta(days=seed % 365)
    raw_payloads = tuple(synthetic_ctrader_payloads(start=start, symbol_id=SYMBOL_ID, count=max(130, event_count)))
    raw_payloads = raw_payloads[:event_count]
    if not raw_payloads:
        raise BenchmarkError("fixture no produjo eventos")
    try:
        report = dependency_report().to_dict()
    except Exception as exc:
        report = {"available": False, "message": f"dependency_report:{type(exc).__name__}"}
    codec: Any | None = None
    codec_report = dict(report)
    if bool(report.get("available")):
        try:
            codec = SdkProtobufCodec()
        except Exception as exc:
            raise BenchmarkError("el codec reportó disponibilidad pero no pudo inicializarse") from exc
    else:
        codec_report.setdefault("message", "codec Protobuf no disponible; se usa fixture JSON aislado")
    frames = _encode_inputs(raw_payloads, codec)
    first_available = datetime.fromtimestamp(int(raw_payloads[0]["timestamp"]) / 1000, UTC) + timedelta(seconds=1)
    end = datetime.fromtimestamp(int(raw_payloads[-1]["timestamp"]) / 1000, UTC) + timedelta(seconds=1)
    end_payload = {
        "state": "END",
        "continuity": "CONTINUOUS",
        "requested_start": instant_text(first_available),
        "requested_end": instant_text(end),
    }
    input_sha256, input_bytes = _hash_frames(frames, end_payload)
    coverage = CaptureCoverage(
        requested_start=first_available,
        requested_end=end,
        observed_start=first_available,
        observed_end=end,
        dataset_end_declared=True,
        continuity="CONTINUOUS",
        availability_known=True,
    )
    codec_report.update(
        {
            "status": "available" if codec is not None else "not_available",
            "backend": report.get("codec_backend") if codec is not None else "fixture_json_fallback",
            "frame_count": len(frames),
        }
    )
    return _PreparedInput(
        seed,
        event_count,
        start,
        frames,
        raw_payloads,
        input_sha256,
        input_bytes,
        coverage,
        codec,
        codec_report,
    )


def _decode_pass(
    prepared: _PreparedInput, *, chunk_size: int, measurement_kind: str
) -> tuple[tuple[CaptureEnvelope, ...], list[Any]]:
    if measurement_kind not in {"timing", "memory"}:
        raise BenchmarkError(f"tipo de medición codec desconocido: {measurement_kind}")
    decoded: list[CaptureEnvelope] = []
    samples: list[Any] = []
    with TemporaryDirectory(prefix="mtf-reliability-codec-") as directory:
        root = Path(directory)
        with _isolated_environment(root), _tracemalloc_state(measurement_kind == "memory"):
            memory_baseline = _MemoryBaseline(_tree_size(root))
            for offset in range(0, len(prepared.frames), chunk_size):
                chunk = prepared.frames[offset : offset + chunk_size]

                def decode_operation(
                    chunk: Sequence[bytes] = chunk, offset: int = offset
                ) -> tuple[CaptureEnvelope, ...]:
                    return _decode_chunk(chunk, offset, prepared.codec, source="mtf-reliability-codec")

                sample: Any
                if measurement_kind == "timing":
                    chunk_result, sample = _measure_speed(decode_operation)
                else:
                    chunk_result, sample = _measure_memory(
                        decode_operation,
                        work_root=root,
                        baseline=memory_baseline,
                    )
                decoded.extend(chunk_result)
                samples.append(sample)
    decoded.append(
        _end_envelope(
            prepared.event_count,
            prepared.coverage.requested_end or prepared.start,
            prepared.coverage.requested_start or prepared.start,
        )
    )
    return tuple(decoded), samples


