def _validate_positive(value: int, name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise ValueError(f"{name} debe ser entero positivo")
    return value


def _maxrss_bytes() -> int:
    """Return process high-water RSS in bytes (Linux is the target host)."""

    value = int(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)
    # Linux reports KiB; macOS reports bytes. Keep the conversion explicit so
    # the JSON field has one unit if the focal test is run elsewhere.
    return value if sys.platform == "darwin" else value * 1024


def _tree_size(root: Path) -> int:
    """Return the present size of benchmark-owned filesystem artifacts."""

    total = 0
    if not root.exists():
        return total
    for path in root.rglob("*"):
        if path.is_file() and not path.is_symlink():
            try:
                total += path.stat().st_size
            except OSError:
                # A disappearing temporary journal is not a functional error;
                # the next sample observes the resulting stable footprint.
                continue
    return total


def _stable(value: Any) -> Any:
    """Remove storage-only identity fields while preserving functional data."""

    if isinstance(value, Mapping):
        return {str(key): _stable(item) for key, item in value.items() if str(key) not in _VOLATILE_KEYS}
    if isinstance(value, (list, tuple)):
        return [_stable(item) for item in value]
    if hasattr(value, "value") and not isinstance(value, (str, bytes, bytearray)):
        enum_value = value.value
        if isinstance(enum_value, (str, int, float, bool)) or enum_value is None:
            return enum_value
    if isinstance(value, datetime):
        return instant_text(value)
    return value


def _quantile(values: Sequence[float], probability: float) -> float | None:
    if not values:
        return None
    ordered = sorted(float(value) for value in values)
    if len(ordered) == 1:
        return ordered[0]
    position = (len(ordered) - 1) * probability
    lower = int(position)
    upper = min(lower + 1, len(ordered) - 1)
    fraction = position - lower
    return ordered[lower] + (ordered[upper] - ordered[lower]) * fraction


def _distribution(values: Iterable[float]) -> dict[str, float | None]:
    materialized = tuple(float(value) for value in values)
    return {
        "p50": _quantile(materialized, 0.50),
        "p95": _quantile(materialized, 0.95),
        "p99": _quantile(materialized, 0.99),
    }


def _timing_summary(samples: Sequence[_SpeedSample]) -> dict[str, Any]:
    return {
        "sample_count": len(samples),
        "wall_seconds": _distribution(sample.wall_ns / 1_000_000_000 for sample in samples),
        "cpu_seconds": _distribution(sample.cpu_ns / 1_000_000_000 for sample in samples),
    }


def _memory_summary(samples: Sequence[_MemorySample]) -> dict[str, Any]:
    return {
        "sample_count": len(samples),
        "maxrss_bytes": _distribution(sample.maxrss_total_bytes for sample in samples),
        "maxrss_scope": "process_high_water_total",
        "python_current_delta_bytes": _distribution(sample.python_current_delta_bytes for sample in samples),
        "python_peak_delta_bytes": _distribution(sample.python_peak_delta_bytes for sample in samples),
        # This is cumulative growth of benchmark-owned SQLite artifacts since
        # the memory-pass baseline, not a claim about write amplification or
        # storage-device I/O.
        "sqlite_artifact_size_bytes": _distribution(sample.sqlite_artifact_bytes for sample in samples),
        "sqlite_artifact_delta_bytes": _distribution(sample.sqlite_artifact_delta_bytes for sample in samples),
        "bytes_work_new": _distribution(sample.bytes_work_new for sample in samples),
    }


def _combined_phase_summary(timing: Sequence[_SpeedSample], memory: Sequence[_MemorySample]) -> dict[str, Any]:
    """Combine independent passes without mixing their measurements."""

    return {
        "timing": _timing_summary(timing),
        "memory": _memory_summary(memory),
        "timing_pass": "speed_without_tracemalloc",
        "memory_pass": "memory_with_tracemalloc",
    }


def _measure_speed(operation: Callable[[], _T]) -> tuple[_T, _SpeedSample]:
    """Measure speed only; tracing must be disabled to avoid instrumentation bias."""

    if tracemalloc.is_tracing():
        raise BenchmarkError("la medición de velocidad requiere tracemalloc desactivado")
    wall_before = time.perf_counter_ns()
    cpu_before = time.process_time_ns()
    result = operation()
    cpu_after = time.process_time_ns()
    wall_after = time.perf_counter_ns()
    return result, _SpeedSample(wall_after - wall_before, cpu_after - cpu_before)


def _measure_memory(
    operation: Callable[[], _T], *, work_root: Path, baseline: _MemoryBaseline
) -> tuple[_T, _MemorySample]:
    """Measure allocations/artifact footprint only; elapsed time is discarded."""

    if not tracemalloc.is_tracing():
        raise BenchmarkError("la medición de memoria requiere tracemalloc activado")
    current_before, _old_peak = tracemalloc.get_traced_memory()
    tracemalloc.reset_peak()
    files_before = _tree_size(work_root)
    result = operation()
    current_after, peak_after = tracemalloc.get_traced_memory()
    files_after = _tree_size(work_root)
    return result, _MemorySample(
        maxrss_total_bytes=_maxrss_bytes(),
        python_current_delta_bytes=current_after - current_before,
        python_peak_delta_bytes=max(0, peak_after - current_before),
        sqlite_artifact_bytes=files_after,
        sqlite_artifact_delta_bytes=files_after - files_before,
        bytes_work_new=max(0, files_after - baseline.sqlite_artifact_bytes),
    )


@contextmanager
def _tracemalloc_state(enabled: bool) -> Iterator[None]:
    """Temporarily force the requested instrumentation state and restore it."""

    was_enabled = tracemalloc.is_tracing()
    if enabled and not was_enabled:
        tracemalloc.start()
    elif not enabled and was_enabled:
        tracemalloc.stop()
    try:
        yield
    finally:
        is_enabled = tracemalloc.is_tracing()
        if was_enabled and not is_enabled:
            tracemalloc.start()
        elif not was_enabled and is_enabled:
            tracemalloc.stop()


@contextmanager
def _isolated_environment(root: Path) -> Iterator[None]:
    """Fence HOME/XDG/TMP and fail if an accidental socket is attempted."""

    paths = {
        "HOME": root / "home",
        "XDG_CONFIG_HOME": root / "xdg-config",
        "XDG_DATA_HOME": root / "xdg-data",
        "XDG_CACHE_HOME": root / "xdg-cache",
        "XDG_STATE_HOME": root / "xdg-state",
        "XDG_RUNTIME_DIR": root / "xdg-runtime",
        "TMPDIR": root / "tmp",
        "TMP": root / "tmp",
        "TEMP": root / "tmp",
        "MTF_LAB_STATE_DIR": root / "mtf-state",
    }
    for path in paths.values():
        path.mkdir(parents=True, exist_ok=True)
    env = {key: str(path) for key, path in paths.items()}
    with (
        patch.dict(os.environ, env),
        patch.object(socket.socket, "connect", side_effect=AssertionError("benchmark network fence")),
        patch.object(socket, "create_connection", side_effect=AssertionError("benchmark network fence")),
    ):
        yield


